// Small deterministic PRNG for content generation. Creating a fresh function
// with the same seed restarts the sequence, which is exactly what a fixed map
// needs when it is generated again after a reload or in a test.
export function seededRandom(seed: number): () => number {
    let state = seed >>> 0;
    return () => {
        state = (state + 0x6d2b79f5) | 0;
        let value = Math.imul(state ^ (state >>> 15), 1 | state);
        value = (value + Math.imul(value ^ (value >>> 7), 61 | value)) ^ value;
        return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
    };
}
